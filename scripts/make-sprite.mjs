// Builds public/icons/sprite.svg from Phosphor (MIT) regular icons, and src/icons.ts with the list.
// Run: node scripts/make-sprite.mjs   (network needed; output is committed)
import { writeFileSync } from "node:fs";

const VERSION = "2.1.1";
export const ICONS = [
  // category icons
  "house", "shopping-cart", "fork-knife", "car", "first-aid-kit", "television", "confetti", "t-shirt",
  "book-open", "paw-print", "gift", "receipt", "package", "briefcase", "laptop", "trend-up", "arrow-u-up-left",
  "tag", "coffee", "airplane", "device-mobile", "plug", "drop", "lightning", "bank", "credit-card", "heart",
  "hammer", "users", "question",
  // chrome
  "plus", "caret-left", "caret-right", "shield-check", "sign-out", "download-simple", "trash", "check", "x",
];

const parts = [];
for (const name of ICONS) {
  const res = await fetch(`https://unpkg.com/@phosphor-icons/core@${VERSION}/assets/regular/${name}.svg`);
  if (!res.ok) throw new Error(`${name}: ${res.status}`);
  const svg = await res.text();
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  parts.push(`<symbol id="${name}" viewBox="0 0 256 256">${inner}</symbol>`);
}
const sprite = `<svg xmlns="http://www.w3.org/2000/svg" style="display:none"><!-- Phosphor Icons ${VERSION}, MIT -->\n${parts.join("\n")}\n</svg>\n`;
writeFileSync(new URL("../public/icons/sprite.svg", import.meta.url), sprite);
// Inlined into every page (Safari is unreliable with external <use> references).
writeFileSync(new URL("../src/sprite.ts", import.meta.url), `// Generated by scripts/make-sprite.mjs\nexport const SPRITE = ${JSON.stringify(sprite)};\n`);
writeFileSync(
  new URL("../src/icons.ts", import.meta.url),
  `// Generated by scripts/make-sprite.mjs. Names available in public/icons/sprite.svg.\nexport const CATEGORY_ICONS = ${JSON.stringify(ICONS.slice(0, 30))} as const;\nexport const ALL_ICONS = ${JSON.stringify(ICONS)} as const;\n`,
);
console.log(`sprite: ${ICONS.length} icons`);
